function makeSheet(name, title, sub, rule, headers, rows, widths, opts = {}) {
  const sheet = opts.sheet ?? wb.worksheets.add(name);
  sheet.showGridLines = false;
  sheet.freezePanes.freezeRows(4);
  sheet.getRange('A1').values = [[title]];
  sheet.getRange('A2').values = [[sub]];
  sheet.getRange('A3').values = [[rule]];
  const lastCol = String.fromCharCode(64 + headers.length);
  const end = 4 + Math.max(rows.length, 1);
  sheet.getRange(`A4:${lastCol}4`).values = [headers];
  if (rows.length) sheet.getRange(`A5:${lastCol}${end}`).values = rows;
  sheet.getRange(`A1:${lastCol}${end}`).format.font = { name: 'Tahoma', size: 10, color: P.ink };
  sheet.getRange('A1').format.font = { name: 'Tahoma', size: 18, bold: true, color: P.ink };
  sheet.getRange('A2:A3').format.font = { name: 'Tahoma', size: 10, color: P.muted };
  sheet.getRange(`A4:${lastCol}4`).format = { fill: P.ink, font: { name: 'Tahoma', size: 10, bold: true, color: P.white } };
  sheet.getRange(`A4:${lastCol}4`).format.rowHeight = 42;
  sheet.getRange(`A5:${lastCol}${end}`).format.rowHeight = opts.rowHeight || 43;
  sheet.getRange(`A4:${lastCol}${end}`).format.verticalAlignment = 'center';
  sheet.getRange(`A4:${lastCol}${end}`).format.borders = { preset: 'inside', style: 'thin', color: P.line };
  widths.forEach((width, i) => sheet.getRangeByIndexes(0, i, end, 1).format.columnWidthPx = width);
  return { sheet, end, lastCol };
}
function colorRows(sheet, rows, lastCol, color) {
  for (const row of rows) sheet.getRange(`A${row}:${lastCol}${row}`).format.fill = color;
}
function addFilter(sheet, lastCol, end, name) {
  const table = sheet.tables.add(`A4:${lastCol}${end}`, true, name);
  table.showFilterButton = true;
}

