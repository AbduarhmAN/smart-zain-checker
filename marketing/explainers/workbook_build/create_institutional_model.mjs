function styleSheet(sheet, lastCol, lastRow, widths) {
  sheet.showGridLines = false;
  sheet.freezePanes.freezeRows(4);
  sheet.getRange(`A1:${lastCol}${lastRow}`).format.font = { name: font, size: 10, color: ink };
  sheet.getRange('A1').format.font = { name: font, size: 19, bold: true, color: ink };
  sheet.getRange('A2:A3').format.font = { name: font, size: 10, color: '#516E79' };
  sheet.getRange(`A4:${lastCol}4`).format = {
    fill: ink,
    font: { name: font, size: 10, bold: true, color: '#FFFFFF' },
  };
  sheet.getRange(`A4:${lastCol}4`).format.rowHeight = 36;
  sheet.getRange(`A5:${lastCol}${lastRow}`).format.rowHeight = 34;
  sheet.getRange(`A4:${lastCol}${lastRow}`).format.verticalAlignment = 'center';
  sheet.getRange(`A4:${lastCol}${lastRow}`).format.borders = {
    preset: 'inside', style: 'thin', color: border,
  };
  widths.forEach((width, index) => {
    sheet.getRangeByIndexes(0, index, lastRow, 1).format.columnWidthPx = width;
  });
}

